package com.codencode;

public class MathLibrary {
    public int add(int a, int b) {
        return a + b;
    }

    public int subtract(int a, int b) {
        return a - b;
    }

    public int product(int a, int b) {
        return a * b;
    }

    public int division(int a, int b) {
        return a/b;
    }
}
